CREATE TABLE GDT_MATERIAS (
    mat_codigo   NUMBER(5) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mat_materia  VARCHAR2(250) NOT NULL,
    CONSTRAINT UQ_MATERIAS_MATERIA UNIQUE (mat_materia)
);

COMMENT ON COLUMN GDT_MATERIAS.mat_codigo  IS 'Codigo unico de la materia';
COMMENT ON COLUMN GDT_MATERIAS.mat_materia IS 'Nombre de la materia';


CREATE TABLE GDT_TAREAS (
    tar_codigo     NUMBER(5) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tar_actividad  VARCHAR2(200) NOT NULL,
    tar_estado     CHAR(1) DEFAULT 'P' NOT NULL,
    tar_fecha      DATE,
    tar_mat_codigo    NUMBER(5) NOT NULL REFERENCES GDT_MATERIAS(mat_codigo),
    tar_prioridad  CHAR(1),
    tar_descripcion VARCHAR2(500),
    CONSTRAINT CK_TAREAS_ESTADO CHECK (tar_estado IN ('P', 'E', 'F')),
    CONSTRAINT CK_TAREAS_PRIORIDAD CHECK (tar_prioridad IN ('B', 'M', 'A'))
);

COMMENT ON COLUMN GDT_TAREAS.tar_codigo     IS 'Codigo unico de cada tarea';
COMMENT ON COLUMN GDT_TAREAS.tar_actividad  IS 'Nombre de la tarea';
COMMENT ON COLUMN GDT_TAREAS.tar_estado     IS 'Estado de la tarea: P = Pendiente, E = En Progreso, F = Finalizada';
COMMENT ON COLUMN GDT_TAREAS.tar_fecha      IS 'Fecha finalizacion de la tarea';
COMMENT ON COLUMN GDT_TAREAS.tar_mat_codigo IS 'Codigo de la materia';
COMMENT ON COLUMN GDT_TAREAS.tar_prioridad  IS 'Prioridad de la tarea: B = Baja, M = Media, A = Alta';
COMMENT ON COLUMN GDT_TAREAS.tar_descripcion      IS 'Descripcion de la tarea';